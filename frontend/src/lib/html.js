// Escapes text for safe insertion into innerHTML — use whenever partner-,
// Kunde-, or import-file-supplied text is interpolated into an HTML string.
export function escapeHtml(value) {
  return String(value ?? "").replace(/[&<>"']/g, (char) => {
    switch (char) {
      case "&":
        return "&amp;";
      case "<":
        return "&lt;";
      case ">":
        return "&gt;";
      case '"':
        return "&quot;";
      default:
        return "&#39;";
    }
  });
}
